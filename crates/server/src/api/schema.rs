//! Filter and SQL schema catalog.
//!
//! Spec 05 § Logical views and § Filter DSL. The UI picks operators from [`ColumnType`];
//! it does not need storage column types. Binary id columns are [`ColumnType::String`] because the
//! views expose hex.

use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

/// Logical views a filter or SQL query can name.
///
/// Spec 05 § Logical views.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "snake_case")]
pub enum ViewName {
    /// Span rows, including heavy payload columns.
    Spans,
    /// One row per trace.
    Traces,
    /// One row per session.
    Sessions,
    /// Score rows.
    Scores,
    /// Experiment item rows.
    ExperimentItems,
    /// Dataset item rows.
    DatasetItems,
}

/// Column type the filter UI understands.
///
/// Spec 05 § Logical views.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "snake_case")]
pub enum ColumnType {
    /// Text, including hex ids.
    String,
    /// Integer, including durations in nanoseconds and token counts.
    Integer,
    /// Floating point, including USD costs.
    Float,
    /// Boolean.
    Boolean,
    /// Instant. JSON values are RFC 3339.
    Timestamp,
    /// List of strings.
    StringList,
    /// String map.
    StringMap,
    /// String column whose text is JSON.
    Json,
}

/// One column of a logical view.
///
/// Spec 05 § Logical views.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct ColumnSchema {
    /// Column name.
    pub name: String,
    /// Type the filter UI uses to pick operators.
    pub column_type: ColumnType,
    /// Whether the column may be null.
    pub nullable: bool,
    /// What the column means.
    pub description: String,
}

/// One logical view.
///
/// Spec 05 § Logical views.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct ViewSchema {
    /// View name.
    pub name: ViewName,
    /// What the view contains.
    pub description: String,
    /// Columns, in spec order.
    pub columns: Vec<ColumnSchema>,
}

/// One function the filter DSL or SQL console can call.
///
/// Spec 05 § Filter DSL.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct FunctionSchema {
    /// Function name.
    pub name: String,
    /// Argument and return types, for example `score(name: string) -> float`.
    pub signature: String,
    /// What the function does.
    pub description: String,
    /// Whether the filter DSL allows the function.
    pub in_filter: bool,
    /// Whether the SQL console allows the function.
    pub in_sql: bool,
}

/// Views and functions the filter builder and SQL console show.
///
/// `GET /api/v1/projects/{project}/schema`. Spec 05 and spec 09 § Observability data.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct SchemaResponse {
    /// Logical views.
    pub views: Vec<ViewSchema>,
    /// Functions.
    pub functions: Vec<FunctionSchema>,
}

#[cfg(test)]
mod tests {
    use super::{ColumnSchema, ColumnType, FunctionSchema, SchemaResponse, ViewName, ViewSchema};
    use std::path::Path;

    fn cell(text: &str) -> String {
        text.replace('|', "\\|").replace('\n', " ")
    }

    fn snake(value: impl serde::Serialize) -> String {
        match serde_json::to_value(value) {
            Ok(serde_json::Value::String(name)) => name,
            other => panic!("expected a string, got {other:?}"),
        }
    }

    /// The SQL schema reference page (D-W-7): every view with its columns, then the functions.
    fn sql_schema_reference() -> String {
        let schema = crate::api::convert::schema_response();
        let mut page = String::from(
            "---\n\
             title: SQL schema\n\
             description: The tables and columns you can query in the SQL console and the filter language.\n\
             ---\n\n\
             <!-- Generated by `just docs-gen` from the server's schema catalog. Do not edit. -->\n\n\
             Each table below is a view of your project's data. The SQL console and the filter language \
             read the same views. Timestamps are integers in nanoseconds since the Unix epoch (UTC), \
             and trace and span IDs are lowercase hex strings.\n",
        );
        for view in &schema.views {
            page.push_str(&format!(
                "\n## `{}`\n\n{}\n\n| Column | Type | Nullable | Description |\n|---|---|---|---|\n",
                snake(view.name),
                view.description
            ));
            for column in &view.columns {
                page.push_str(&format!(
                    "| `{}` | `{}` | {} | {} |\n",
                    column.name,
                    snake(column.column_type),
                    if column.nullable { "yes" } else { "no" },
                    cell(&column.description)
                ));
            }
        }
        page.push_str("\n## Functions\n\n| Function | Description |\n|---|---|\n");
        for function in &schema.functions {
            page.push_str(&format!(
                "| `{}` | {} |\n",
                cell(&function.signature),
                cell(&function.description)
            ));
        }
        page
    }

    #[test]
    fn sql_schema_reference_is_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../website/src/content/docs/docs/reference/sql-schema.md");
        let expected = sql_schema_reference();
        if std::env::var_os("CETRA_DOCS_WRITE").is_some() {
            std::fs::write(&path, &expected).expect("write the SQL schema reference");
            return;
        }
        let actual = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            actual == expected,
            "website/src/content/docs/docs/reference/sql-schema.md is stale: run `just docs-gen`"
        );
    }

    #[test]
    fn schema_response_snapshot() {
        let response = SchemaResponse {
            views: vec![ViewSchema {
                name: ViewName::Traces,
                description: "One row per trace.".to_owned(),
                columns: vec![ColumnSchema {
                    name: "trace_id".to_owned(),
                    column_type: ColumnType::String,
                    nullable: false,
                    description: "Trace id, 16 bytes as lowercase hex.".to_owned(),
                }],
            }],
            functions: vec![FunctionSchema {
                name: "score".to_owned(),
                signature: "score(name: string) -> float".to_owned(),
                description: "Latest numeric value of the named score.".to_owned(),
                in_filter: true,
                in_sql: false,
            }],
        };

        insta::with_settings!({
            snapshot_path => "../../tests/snapshots",
            prepend_module_to_snapshot => false,
        }, {
            insta::assert_snapshot!(
                "schema_response",
                serde_json::to_string_pretty(&response).unwrap()
            );
        });
    }
}
